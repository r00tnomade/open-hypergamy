"""Regenerate the architecture section of README.md from a graphify code graph.

    graphify update src && python3 scripts/update_architecture.py   # refresh
    python3 scripts/update_architecture.py --check                   # exit 1 if README is stale
    python3 scripts/update_architecture.py --run                     # run `graphify update src` first

Only the text between the architecture markers in README.md is rewritten. Every number and claim in
that block is computed from graph.json; nothing in it is hand-maintained. Standard library only.
"""
# ruff: noqa: E501

import argparse
import json
import re
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
GRAPH = ROOT / "src" / "graphify-out" / "graph.json"
START, END = (
    "<!-- architecture:start (generated by scripts/update_architecture.py) -->",
    "<!-- architecture:end -->",
)
CORE = [
    "cli", "sources", "discovery", "extraction", "llm", "verification", "persistence",
    "scoring", "monitoring", "notifications", "reporting", "scheduling", "observability",
]  # fmt: skip
SHARED = ("clock", "errors", "config", "domain")
MIN_USES = 7


def package(source_file: str | None) -> str | None:
    m = re.match(r"src/open_hypergamy/([^/.]+)(?:/|\.py)", source_file or "")
    if not m:
        return None
    return "cli" if m[1] in ("cli_ops", "cli_common") else m[1]


def render(graph: dict) -> str:
    nodes, links = graph["nodes"], graph["links"]
    pkg = {n["id"]: package(n.get("source_file")) for n in nodes}
    size = Counter(p for p in pkg.values() if p)
    uses: Counter[tuple[str, str]] = Counter()
    degree: Counter[str] = Counter()
    into_cli = sources_to_discovery = 0
    for e in links:
        degree[e["source"]] += 1
        degree[e["target"]] += 1
        a, b = pkg.get(e["source"]), pkg.get(e["target"])
        if not a or not b or a == b:
            continue
        into_cli += b == "cli"
        sources_to_discovery += (a, b) == ("sources", "discovery")
        if a in CORE and b in CORE and e.get("confidence") == "EXTRACTED":
            uses[(a, b)] += 1
    label = {n["id"]: n["label"] for n in nodes}
    hubs = [
        f"`{label[i]}` ({d})"
        for i, d in degree.most_common(40)
        if not label[i].endswith(("()", ".py"))
    ][:3]
    mermaid = ["```mermaid", "flowchart LR"]
    mermaid += [f'  {n}["{n}<br/>{size[n]} nodes"]' for n in CORE if size[n]]
    mermaid += [f"  {a} -->|{c}| {b}" for (a, b), c in uses.most_common() if c >= MIN_USES]
    mermaid.append("```")
    facts = [
        f"- **One-way flow.** Edges from `sources` into `discovery`: **{sources_to_discovery}**."
        if sources_to_discovery
        else "- **One-way flow.** Nothing in `sources` calls back into `discovery`.",
        f"- **Edges pointing into the CLI layer:** **{into_cli}**."
        if into_cli
        else "- **The CLI is a thin shell.** Nothing points into `cli`; it only calls service packages.",
        f"- **Hubs.** The most connected nodes are {', '.join(hubs)}.",
    ]
    return "\n".join(
        [
            START,
            f"Generated from the code, not drawn by hand: [graphify](https://github.com/Graphify-Labs/graphify) "
            f"parsed `src/` with tree-sitter (no LLM involved) into **{len(nodes)} nodes and {len(links)} edges**. "
            f"Nodes are grouped by package. An arrow `a -->|n| b` means `a` calls, imports or uses `b` in `n` places. "
            f"Only edges read directly from the source are counted, arrows under {MIN_USES} uses are hidden, and the "
            f"shared plumbing ({', '.join(f'`{s}`' for s in SHARED)}) is left out because nearly everything uses it.",
            "",
            *mermaid,
            "",
            *facts,
            "",
            "Refresh with `graphify update src && python3 scripts/update_architecture.py`; "
            "`--check` fails if this block is stale. Open `src/graphify-out/graph.html` for the interactive graph "
            "(the output folder is gitignored).",
            END,
        ]
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument(
        "--check", action="store_true", help="exit 1 if the README block is out of date"
    )
    ap.add_argument("--run", action="store_true", help="run `graphify update src` first")
    ap.add_argument("--graph", type=Path, default=GRAPH)
    args = ap.parse_args()
    if args.run:
        exe = shutil.which("graphify")
        if not exe:
            print("graphify is not on PATH (uv tool install graphifyy)", file=sys.stderr)
            return 2
        subprocess.run([exe, "update", "src"], cwd=ROOT, check=True)
    if not args.graph.is_file():
        print(f"{args.graph} not found: run `graphify update src` first", file=sys.stderr)
        return 2
    text = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        print("architecture markers not found in README.md", file=sys.stderr)
        return 2
    new = pattern.sub(lambda _: render(json.loads(args.graph.read_text(encoding="utf-8"))), text)
    if new == text:
        print("architecture block is up to date")
        return 0
    if args.check:
        print("architecture block is stale: run scripts/update_architecture.py", file=sys.stderr)
        return 1
    README.write_text(new, encoding="utf-8")
    print("README architecture block updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
